// 시트 저장용 포맷터 — UI 선택값을 "종류(상세)" 한 문자열로.
// 상세가 비어 있으면 종류명만 반환.
//   예: formatWorkType('KV', '베이직') → 'KV(베이직)'
//       formatWorkType('카드뉴스', '') → '카드뉴스'
export function formatWorkType(category: string, detail: string): string {
  if (!category) return ''
  return detail ? `${category}(${detail})` : category
}
